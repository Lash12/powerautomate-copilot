/**
 * Returns expression functions that match the given query (name, category, description)
 * and optionally filtered to a single category.
 */
export function searchExpressions(
  query?: string,
  category?: ExpressionCategory
): ExpressionFunction[] {
  const q = query?.toLowerCase() ?? '';
  return EXPRESSION_FUNCTIONS.filter((fn) => {
    const categoryMatch = !category || fn.category === category;
    if (!q) {
      return categoryMatch;
    }
    const textMatch =
      fn.name.toLowerCase().includes(q) ||
      fn.description.toLowerCase().includes(q) ||
      fn.syntax.toLowerCase().includes(q) ||
      fn.category.toLowerCase().includes(q);
    return categoryMatch && textMatch;
  });
}
